const UNSPLASH_PHOTO_ID =
  /^https:\/\/images\.unsplash\.com\/photo-([0-9a-f]+-[0-9a-f]+)/;

/**
 * Image source for a stored plan image: the bundled asset for a known
 * Unsplash URL, otherwise the URI itself (a device photo or an unknown URL).
 */
export const planImageSource = (url: string): number | { uri: string } => {
  const id = UNSPLASH_PHOTO_ID.exec(url)?.[1];
  const bundled = id ? bundledPlanImages[id] : undefined;
  return bundled ?? { uri: url };
};
